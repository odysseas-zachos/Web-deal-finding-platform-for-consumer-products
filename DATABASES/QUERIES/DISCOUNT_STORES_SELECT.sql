DELIMITER $
DROP PROCEDURE IF EXISTS Store_Discounts_By_Cat$
CREATE PROCEDURE Store_Discounts_By_Cat (IN CATEGORY_VAR VARCHAR(50))
BEGIN

SELECT STORE_GEOJSON.X, STORE_GEOJSON.Y, STORE_GEOJSON.NAME, STORE_GEOJSON.ID, STORE.DISCOUNTS, STORE.ID, PRODUCT.PRODUCT_NAME, CATEGORIES.CATEGORY_NAME FROM store_geojson
INNER JOIN STORE ON STORE_GEOJSON.ID = STORE.STORE_GEOJSON_ID
INNER JOIN DISCOUNT ON STORE.ID = DISCOUNT.DISCOUNT_STORE_ID
INNER JOIN PRODUCT ON DISCOUNT_PRODUCT_NAME = PRODUCT.PRODUCT_NAME
INNER JOIN CATEGORIES ON PRODUCT.PRODUCT_CATEGORY = CATEGORIES.CATEGORY_ID
WHERE CATEGORIES.CATEGORY_NAME = CATEGORY_VAR;

END$

DELIMITER ;

CALL Store_Discounts_By_Cat ('Ποτά - Αναψυκτικά');