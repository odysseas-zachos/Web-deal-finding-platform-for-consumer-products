DROP DATABASE IF EXISTS WEB_DB;
CREATE DATABASE WEB_DB;
USE WEB_DB;


CREATE TABLE USER (
USER_ID SMALLINT UNSIGNED NOT NULL AUTO_INCREMENT,
USERNAME VARCHAR(25) NOT NULL,
PASSWORD VARCHAR(25) NOT NULL,
STATUS ENUM ('USER', 'ADMIN') DEFAULT 'USER',
TOKENS SMALLINT UNSIGNED DEFAULT 0,
DISCOUNTS SMALLINT UNSIGNED NOT NULL DEFAULT 0, -- count of discounts updated by trigger before insert on discount table
PRIMARY KEY (USER_ID)
)ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

