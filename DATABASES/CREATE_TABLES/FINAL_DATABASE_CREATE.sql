 CREATE TABLE CATEGORIES (
 CATEGORY_ID VARCHAR(50) NOT NULL,
 CATEGORY_NAME VARCHAR(50),
 PRIMARY KEY (CATEGORY_ID)
 )ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
 
 CREATE TABLE SUBCATEGORIES (
 SUBCATEGORY_UUID VARCHAR(50) NOT NULL,
 SUBCATEGORY_NAME VARCHAR(50),
 PARENT_CATEGORY_ID VARCHAR(50),
 PRIMARY KEY (SUBCATEGORY_UUID),
 CONSTRAINT PRNT_CATEG FOREIGN KEY (PARENT_CATEGORY_ID) REFERENCES CATEGORIES(CATEGORY_ID) ON DELETE SET NULL ON UPDATE CASCADE
 )ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
 
  
CREATE TABLE PRODUCT (
  PRODUCT_ID SMALLINT UNSIGNED NOT NULL,
  PRODUCT_NAME VARCHAR(150) NOT NULL,
  PRODUCT_CATEGORY VARCHAR(50) NOT NULL,
  PRODUCT_SUBCATEGORY VARCHAR(50) NOT NULL,
  -- PRODUCT_PRICE DECIMAL(7,2) NOT NULL,
  NEW_ID SMALLINT UNSIGNED NOT NULL AUTO_INCREMENT,	-- NOT SURE IF NEEDED
  UNIQUE(NEW_ID),
  PRIMARY KEY (PRODUCT_NAME),
  CONSTRAINT PRD_CAT FOREIGN KEY (PRODUCT_CATEGORY) REFERENCES CATEGORIES(CATEGORY_ID) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT PRD_SUBCAT FOREIGN KEY (PRODUCT_SUBCATEGORY) REFERENCES SUBCATEGORIES(SUBCATEGORY_UUID) ON DELETE CASCADE ON UPDATE CASCADE
  )ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
 
 CREATE TABLE PRICE_HISTORY (
 PRICE_RECORD_ID SMALLINT NOT NULL AUTO_INCREMENT,
 PRODUCT_NAME VARCHAR(150) NOT NULL,
 PRICE_RECORD_DATE DATE,
 PRICE_RECORD_PRICE DECIMAL(7,2) NOT NULL,
 PRIMARY KEY(PRICE_RECORD_ID),
 CONSTRAINT PRICEREC_PROD FOREIGN KEY (PRODUCT_NAME) REFERENCES PRODUCT(PRODUCT_NAME) ON DELETE RESTRICT ON UPDATE CASCADE
 )ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
 
 CREATE TABLE STORE( -- Seperation of GeoJSON given Data and Other Useful Data
 ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
 DISCOUNTS BOOLEAN DEFAULT FALSE,/*TO ADD DISOUNTS BY CATEGORY AND DISCOUNTS IN GENERAL*/
 STORE_GEOJSON_ID VARCHAR(15),
 PRIMARY KEY(ID),
 CONSTRAINT STR_GEOJSON FOREIGN KEY(STORE_GEOJSON_ID) REFERENCES STORE_GEOJSON(ID) ON DELETE SET NULL ON UPDATE CASCADE
 )ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
 
 CREATE TABLE PRICE_IN_STORE (
 PRICE_IN_STORE_ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
 PRODUCT_NAME VARCHAR(150),
 STORE_ID INT UNSIGNED,
 PRICE DECIMAL(7,2),
 PRIMARY KEY(PRICE_IN_STORE_ID),
 CONSTRAINT STR_ID FOREIGN KEY(STORE_ID) REFERENCES STORE(ID) ON DELETE SET NULL ON UPDATE CASCADE,
 CONSTRAINT PRD_NAME FOREIGN KEY(PRODUCT_NAME) REFERENCES PRODUCT(PRODUCT_NAME) ON DELETE SET NULL ON UPDATE CASCADE
 )ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE DISCOUNT (
 DISCOUNT_ID SMALLINT UNSIGNED NOT NULL AUTO_INCREMENT,
 DISCOUNT_STORE_ID INT UNSIGNED,
 DISCOUNT_PRODUCT_NAME VARCHAR(150) NOT NULL,
 DISCOUNT_DATE DATE DEFAULT (CURRENT_DATE),
 NEW_PRICE DECIMAL(7,2) NOT NULL,
 USER_ID SMALLINT UNSIGNED,
 -- DISCOUNT_CRITERION_1 BOOLEAN NOT NULL DEFAULT FALSE,		
 -- DISCOUNT_CRITERION_2 BOOLEAN NOT NULL DEFAULT FALSE,
 DISCOUNT_AVAILIBILITY BOOLEAN NOT NULL DEFAULT TRUE, -- ηταν false το έκανα true (Οδυσσεας) 
 DISCOUNT_LIKES SMALLINT UNSIGNED NOT NULL DEFAULT 0,
 DISCOUNT_DISLIKES SMALLINT UNSIGNED NOT NULL DEFAULT 0,
 PRIMARY KEY (DISCOUNT_ID),
 CONSTRAINT DSC_USR FOREIGN KEY (USER_ID) REFERENCES USER(USER_ID) ON DELETE SET NULL ON UPDATE CASCADE,
 CONSTRAINT DSC_STR FOREIGN KEY (DISCOUNT_STORE_ID) REFERENCES STORE(ID) ON DELETE SET NULL ON UPDATE CASCADE,
 CONSTRAINT DSC_PRDCT FOREIGN KEY (DISCOUNT_PRODUCT_NAME) REFERENCES PRODUCT(PRODUCT_NAME) ON DELETE RESTRICT ON UPDATE CASCADE
 )ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
