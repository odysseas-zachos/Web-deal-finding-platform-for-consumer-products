use web_db;


DROP TRIGGER IF EXISTS discount_likes_gives_tokens;
DELIMITER $

CREATE TRIGGER discount_likes_gives_tokens
AFTER UPDATE ON DISCOUNT
FOR EACH ROW 
BEGIN
UPDATE USER
SET TOKENS = TOKENS + 5
WHERE (NEW.DISCOUNT_LIKES = OLD.DISCOUNT_LIKES + 1 AND USER.USER_ID=NEW.USER_ID);
END$

DELIMITER ;


DROP TRIGGER IF EXISTS discount_dislikes_subtracts_tokens;


DELIMITER $
CREATE TRIGGER discount_dislikes_subtracts_tokens
AFTER UPDATE ON DISCOUNT
FOR EACH ROW 
BEGIN
UPDATE USER
SET TOKENS = TOKENS - 1
WHERE (NEW.DISCOUNT_DISLIKES = OLD.DISCOUNT_LIKES + 1 AND USER.USER_ID=NEW.USER_ID); 
END$
DELIMITER ;