DROP TRIGGER IF EXISTS update_product_price_after_discount_placement;

DELIMITER $
CREATE TRIGGER update_product_price_after_discount_placement BEFORE INSERT ON DISCOUNT
FOR EACH ROW 
BEGIN 
select PRICE INTO @compare_price from PRICE_IN_STORE WHERE PRODUCT_NAME = NEW.DISCOUNT_PRODUCT_NAME AND STORE_ID=NEW.DISCOUNT_STORE_ID;
IF NEW.NEW_PRICE < @compare_price
THEN
UPDATE PRICE_IN_STORE
SET PRICE = NEW.NEW_PRICE
WHERE product_name=NEW.DISCOUNT_PRODUCT_NAME AND STORE_ID = NEW.DISCOUNT_STORE_ID;
UPDATE STORE 
SET DISCOUNTS = TRUE
WHERE ID=NEW.DISCOUNT_STORE_ID;
ELSE 
SET NEW.DISCOUNT_AVAILIBILITY=FALSE;

END IF;
END$

DELIMITER ;

DROP TRIGGER IF EXISTS update_product_price_after_discount_delete;

DELIMITER $
CREATE TRIGGER update_product_price_after_discount_delete AFTER DELETE ON DISCOUNT
FOR EACH ROW 
BEGIN
SET @product_name = OLD.DISCOUNT_PRODUCT_NAME;
SET @disc_store = OLD.DISCOUNT_STORE_ID;
SELECT MAX(PRICE_RECORD_DATE) INTO @Last_Date FROM price_history WHERE PRODUCT_NAME = @product_name;
SELECT PRICE_RECORD_PRICE INTO @Last_Price FROM price_history where PRICE_RECORD_DATE=@Last_Date and PRODUCT_NAME = @product_name;
UPDATE PRICE_IN_STORE
SET PRICE = @Last_Price
WHERE product_name=@product_name AND STORE_ID=@disc_store;
SELECT COUNT(*) INTO @Discount_Count FROM DISCOUNT WHERE DISCOUNT_STORE_ID = @disc_store;
IF @Discount_Count=0 THEN
UPDATE STORE 
SET DISCOUNTS = FALSE
WHERE ID=@disc_store;
END IF;
END$
